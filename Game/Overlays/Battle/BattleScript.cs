    // OFFSET 0x022405FC
    public static int BattleScript_Exec(BattleSystem battleSys, BattleContext battleCtx)
    {
        int result;
        do
        {
            result = sBattleCommands[battleCtx.BattleScript[battleCtx.ScriptCursor]](battleSys, battleCtx);
        }
        while (battleCtx.BattleProgressFlag == 0 && (BattleSystems.BattleSystem_GetBattleType(battleSys) & BattleSystems.BattleTypeLink) == 0);
        battleCtx.BattleProgressFlag = 0;
        return result;
    }
